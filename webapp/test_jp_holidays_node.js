const errors = [];
for (const [i, row] of official.entries()) {
  const year = 2000 + i;
  for (const [j, group] of row.split("/").entries()) {
    const expected = group === "-" ? [] : group.split(",").map(Number);
    const actual = T.calendars.byId.jp.holidays(year, j + 1);
    if (JSON.stringify(actual) !== JSON.stringify(expected)) errors.push(`${year}-${j + 1}: expected [${expected}], got [${actual}]`);
  }
}
assert.deepEqual(errors, [], "every month must match the published dates");
